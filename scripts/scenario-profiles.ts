export function scenarioProfile(index: number) {
  const profileIndex = index % scenarioProfiles.length;
  const profile = scenarioProfiles[profileIndex];
  const object =
    profile.objects[
      Math.floor(index / scenarioProfiles.length) % profile.objects.length
    ];
  const site = sites[Math.floor(index / 80) % sites.length];
  const reference = technologyReference[profile.reference];
  return {
    ...profile,
    profileIndex,
    name: profile.title(object),
    description: `${profile.operation(object)}. Цель применения — ${profile.challenge.toLowerCase()} в процессе «${profile.process.toLowerCase()}». Рассматривается вариант для вымышленной площадки «${site}».`,
    groupId: functionalGroupId(profile.group),
    processId: demoId(`scenario-process:${profileIndex}`),
    taskId: demoId(`scenario-task:${profileIndex}`),
    methodId: referenceMethodId(reference[0], reference[1], reference[2]),
  };
}
